import { ArrowUpRight, GitMerge, RefreshCw, Sparkles, TriangleAlert } from 'lucide-react'
import { useEffect, useState } from 'react'

import { api, errorMessage } from '../../api/client'
import type { MergePreview, MergeResult, MergeSummary } from '../../api/types'
import { branchAncestors } from '../../lib/branchTree'
import { plural } from '../../lib/format'
import { useOperationsStore } from '../../store/operations'
import { useUiStore } from '../../store/ui'
import { useWorkspaceStore } from '../../store/workspace'
import { Button } from '../ui/Button'
import { Dialog } from '../ui/Dialog'
import { Field, Textarea } from '../ui/Field'
import { Spinner } from '../ui/Spinner'
import { MemoryChoice } from './MemoryChoice'

export function MergeDialog({ sourceBranchId }: { sourceBranchId: string }) {
  const close = useOperationsStore((state) => state.closeMerge)
  const refreshSync = useOperationsStore((state) => state.refreshSync)
  const source = useWorkspaceStore((state) =>
    state.branches.find((item) => item.id === sourceBranchId),
  )
  const branches = useWorkspaceStore((state) => state.branches)
  const upsertBranch = useWorkspaceStore((state) => state.upsertBranch)
  const pushToast = useUiStore((state) => state.pushToast)
  const ancestors = branchAncestors(branches, sourceBranchId).filter(
    (branch) => !branch.archived,
  )
  const [targetId, setTargetId] = useState(ancestors[0]?.id ?? '')
  const [preview, setPreview] = useState<MergePreview | null>(null)
  const [selected, setSelected] = useState<Set<string>>(new Set())
  const [summary, setSummary] = useState('')
  const [summaryNote, setSummaryNote] = useState<string | null>(null)
  const [query, setQuery] = useState('')
  const [loading, setLoading] = useState(Boolean(targetId))
  const [loadError, setLoadError] = useState<string | null>(null)
  const [submitError, setSubmitError] = useState<string | null>(null)
  const [generating, setGenerating] = useState(false)
  const [submitting, setSubmitting] = useState(false)
  const [reloadKey, setReloadKey] = useState(0)

  useEffect(() => {
    if (!targetId) return
    const controller = new AbortController()
    api
      .get<MergePreview>(
        `/branches/${sourceBranchId}/merge-preview?target=${encodeURIComponent(targetId)}`,
        controller.signal,
      )
      .then((result) => {
        setPreview(result)
        setSelected(new Set(result.memories.map((memory) => memory.id)))
        setSummary('')
        setSummaryNote(null)
        setSubmitError(null)
        setLoading(false)
      })
      .catch((caught) => {
        if (controller.signal.aborted) return
        setLoadError(errorMessage(caught))
        setLoading(false)
      })
    return () => controller.abort()
  }, [reloadKey, sourceBranchId, targetId])

  const memories = preview?.memories ?? []
  const duplicateIds = new Set(preview?.duplicates.map((item) => item.memory_id) ?? [])
  const normalizedQuery = query.trim().toLowerCase()
  const filtered = normalizedQuery
    ? memories.filter((memory) => memory.content.toLowerCase().includes(normalizedQuery))
    : memories
  const target = ancestors.find((branch) => branch.id === targetId)
  const changeTarget = (nextTargetId: string) => {
    setTargetId(nextTargetId)
    setLoading(true)
    setLoadError(null)
    setPreview(null)
    setSelected(new Set())
    setSummary('')
    setSummaryNote(null)
    setSubmitError(null)
  }
  const retryPreview = () => {
    setLoading(true)
    setLoadError(null)
    setReloadKey((value) => value + 1)
  }
  const canSubmit =
    Boolean(preview) &&
    (selected.size > 0 || summary.trim().length > 0) &&
    !generating &&
    !submitting

  const toggleSelected = (memoryId: string) => {
    setSelected((current) => {
      const next = new Set(current)
      if (next.has(memoryId)) next.delete(memoryId)
      else next.add(memoryId)
      return next
    })
  }

  const generateSummary = async () => {
    if (!preview || selected.size === 0) return
    setGenerating(true)
    setSubmitError(null)
    try {
      const result = await api.post<MergeSummary>(
        `/branches/${sourceBranchId}/merge-summary`,
        { target_branch_id: preview.target_branch_id, memory_ids: [...selected] },
      )
      setSummary(result.summary)
      setSummaryNote(
        result.warning ??
          (result.mock
            ? 'Generated locally in mock mode.'
            : `Generated by ${result.provider}.`),
      )
    } catch (caught) {
      setSubmitError(errorMessage(caught))
    } finally {
      setGenerating(false)
    }
  }

  const submit = async () => {
    if (!preview || !canSubmit) return
    setSubmitting(true)
    setSubmitError(null)
    try {
      const result = await api.post<MergeResult>(
        `/branches/${sourceBranchId}/merge`,
        {
          target_branch_id: preview.target_branch_id,
          memory_ids: [...selected],
          summary: summary.trim(),
          expected_head_id: preview.target_head_commit_id,
        },
      )
      upsertBranch(result.target)
      refreshSync()
      const added =
        result.copied_count > 0
          ? `${plural(result.copied_count, 'memory', 'memories')} added to ${result.target.name}.`
          : `A summary was added to ${result.target.name}.`
      const skipped =
        result.duplicates.length > 0
          ? ` ${plural(
              result.duplicates.length,
              'duplicate skipped',
              'duplicates skipped',
            )}.`
          : ''
      pushToast('success', 'Memories merged up', `${added}${skipped}`)
      close()
    } catch (caught) {
      setSubmitError(errorMessage(caught))
    } finally {
      setSubmitting(false)
    }
  }

  const footer = (
    <div className="flex items-center justify-between gap-3">
      <span className="text-[10px] text-muted">
        {selected.size} of {memories.length} selected
      </span>
      <div className="flex items-center gap-2">
        <Button variant="ghost" size="sm" onClick={close}>
          Cancel
        </Button>
        <Button
          size="sm"
          onClick={() => void submit()}
          loading={submitting}
          disabled={!canSubmit}
          leadingIcon={<GitMerge size={13} aria-hidden />}
        >
          Merge up
        </Button>
      </div>
    </div>
  )

  return (
    <Dialog
      open
      onClose={close}
      title="Merge memories up"
      description="Send selected memories to an ancestor branch. Raw messages are never copied."
      footer={footer}
      size="md"
    >
      {ancestors.length === 0 ? (
        <div className="rounded-xl border border-border bg-subtle/55 p-5 text-center">
          <GitMerge size={20} className="mx-auto text-muted" aria-hidden />
          <p className="mt-2 text-xs font-medium text-ink">No active ancestor to merge into</p>
          <p className="mt-1 text-[11px] text-muted">
            {source?.parent_branch_id
              ? 'Restore an archived ancestor before merging memories upward.'
              : 'This is the root branch. Fork a branch first, then merge memories upward.'}
          </p>
        </div>
      ) : (
        <div className="space-y-4">
          <Field
            label="Merge into"
            htmlFor="merge-target"
            hint="Merging only moves upward to a branch in this lineage."
          >
            <select
              id="merge-target"
              value={targetId}
              onChange={(event) => changeTarget(event.target.value)}
              className="w-full rounded-xl border border-border bg-surface px-3.5 py-2.5 text-sm text-ink shadow-soft focus:border-accent focus:outline-none focus:ring-2 focus:ring-accent/15"
            >
              {ancestors.map((branch) => (
                <option key={branch.id} value={branch.id}>
                  {branch.name}
                </option>
              ))}
            </select>
          </Field>

          <div className="rounded-xl border border-border bg-subtle/55 px-3 py-2.5">
            <p className="flex items-center gap-2 text-[11px] text-muted">
              <ArrowUpRight size={13} className="shrink-0 text-accent" aria-hidden />
              <span>
                <span className="font-medium text-ink">{source?.name ?? 'This branch'}</span>
                {' '}→{' '}
                <span className="font-medium text-ink">
                  {preview?.target_name ?? target?.name ?? 'Ancestor'}
                </span>
              </span>
            </p>
          </div>

          <div>
            <div className="flex items-center justify-between gap-2">
              <p className="text-[10px] font-medium tracking-wide text-muted uppercase">
                New memories on this branch
              </p>
              {preview && memories.length > 0 && (
                <button
                  type="button"
                  onClick={() =>
                    setSelected(
                      selected.size === memories.length
                        ? new Set()
                        : new Set(memories.map((memory) => memory.id)),
                    )
                  }
                  className="text-[10px] font-medium text-accent-ink hover:underline"
                >
                  {selected.size === memories.length ? 'Select none' : 'Select all'}
                </button>
              )}
            </div>

            {loading ? (
              <div className="flex justify-center py-9 text-muted">
                <Spinner className="size-5" />
              </div>
            ) : loadError ? (
              <div className="py-7 text-center">
                <p className="text-[11px] text-danger">{loadError}</p>
                <button
                  type="button"
                  onClick={retryPreview}
                  className="mt-2 inline-flex items-center gap-1 text-[11px] font-medium text-accent-ink hover:underline"
                >
                  <RefreshCw size={11} aria-hidden />
                  Try again
                </button>
              </div>
            ) : memories.length === 0 ? (
              <p className="rounded-lg bg-subtle px-3 py-4 text-center text-[11px] text-muted">
                This branch has no memories that the target does not already have.
                You can still merge a summary.
              </p>
            ) : (
              <>
                {memories.length > 5 && (
                  <input
                    type="search"
                    value={query}
                    onChange={(event) => setQuery(event.target.value)}
                    placeholder="Search memories…"
                    aria-label="Search memories to merge"
                    className="mt-2 h-8 w-full rounded-lg border border-border bg-bg/50 px-3 text-[11px] text-ink placeholder:text-muted/70 focus:border-accent focus:outline-none"
                  />
                )}
                <div className="mt-2 space-y-2">
                  {filtered.map((memory) => (
                    <MemoryChoice
                      key={memory.id}
                      memory={memory}
                      checked={selected.has(memory.id)}
                      duplicate={duplicateIds.has(memory.id)}
                      onToggle={() => toggleSelected(memory.id)}
                    />
                  ))}
                </div>
                {filtered.length === 0 && (
                  <p className="py-4 text-center text-[11px] text-muted">
                    No memories match this search.
                  </p>
                )}
              </>
            )}

            {(preview?.warnings.length ?? 0) > 0 && (
              <div className="mt-3 space-y-1.5">
                {preview?.warnings.map((warning) => (
                  <p
                    key={warning}
                    className="flex items-start gap-1.5 rounded-lg bg-warning-soft px-2.5 py-2 text-[10px] leading-relaxed text-warning"
                  >
                    <TriangleAlert size={11} className="mt-0.5 shrink-0" aria-hidden />
                    {warning}
                  </p>
                ))}
              </div>
            )}

            {duplicateIds.size > 0 && (
              <p className="mt-2 text-[10px] text-muted">
                Near-duplicate memories are marked and skipped during the merge.
              </p>
            )}
          </div>

          <Field
            label="Merge summary"
            htmlFor="merge-summary"
            optional
            hint="Stored on the target branch. Messages themselves are not copied."
          >
            <Textarea
              id="merge-summary"
              value={summary}
              onChange={(event) => setSummary(event.target.value)}
              rows={3}
              maxLength={8000}
              placeholder="What should the ancestor remember from this branch?"
            />
          </Field>
          <div className="-mt-2 flex items-center justify-between gap-2">
            <span className="text-[10px] text-muted">{summaryNote}</span>
            <Button
              variant="secondary"
              size="sm"
              onClick={() => void generateSummary()}
              loading={generating}
              disabled={selected.size === 0}
              leadingIcon={!generating ? <Sparkles size={12} aria-hidden /> : undefined}
            >
              Generate summary
            </Button>
          </div>

          <p className="rounded-lg bg-subtle px-3 py-2.5 text-[10px] leading-relaxed text-muted">
            Messages are not copied. Only the selected memories and this summary move
            into the ancestor branch.
          </p>

          {submitError && (
            <p role="alert" className="rounded-lg bg-danger-soft px-3 py-2 text-xs text-danger">
              {submitError}
            </p>
          )}
        </div>
      )}
    </Dialog>
  )
}
